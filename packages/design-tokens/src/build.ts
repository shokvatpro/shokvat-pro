/**
 * Builds the token outputs:
 *   dist/tokens.css          CSS custom properties (light, dark, system)
 *   dist/tailwind-theme.css  Tailwind v4 theme mapping semantic tokens → utilities
 *   dist/tokens.json         Flat resolved tokens (for mobile apps / other tools)
 *   src/generated.ts         Typed token names
 * Run: pnpm tokens
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { loadPrimitives, loadTheme } from './tokens.ts';

const pkg = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(pkg, 'dist');
mkdirSync(dist, { recursive: true });

const HEADER = '/* Generated by @shokfat/design-tokens — do not edit by hand. Edit tokens/*.json and run `pnpm tokens`. */\n';

const primitives = loadPrimitives();
const light = loadTheme('light');
const dark = loadTheme('dark');

const lightKeys = Object.keys(light).sort();
const darkKeys = Object.keys(dark).sort();
if (lightKeys.join() !== darkKeys.join()) {
  const missing = lightKeys.filter((k) => !darkKeys.includes(k)).concat(darkKeys.filter((k) => !lightKeys.includes(k)));
  throw new Error(`Light and dark themes must define the same tokens. Mismatch: ${missing.join(', ')}`);
}

const fontStack = (key: string) => (primitives[key] as string[]).map((f) => (f.includes(' ') ? `"${f}"` : f)).join(', ');

const staticVars: Record<string, string> = {
  'font-display': fontStack('font.display'),
  'font-body': fontStack('font.body'),
  'font-mono': fontStack('font.mono'),
  'radius-sm': String(primitives['radius.sm']),
  'radius-md': String(primitives['radius.md']),
  'radius-lg': String(primitives['radius.lg']),
  'radius-full': String(primitives['radius.full']),
  'size-touch': String(primitives['size.touch']),
  'shadow-overlay': String(primitives['shadow.overlay']),
  'motion-fast': String(primitives['motion.fast']),
  'motion-base': String(primitives['motion.base']),
};

const block = (vars: Record<string, string>) =>
  Object.entries(vars).map(([k, v]) => `  --sp-${k}: ${v};`).join('\n');

const tenantDefaults = '  --sp-tenant-accent: var(--sp-primary);\n  --sp-on-tenant-accent: var(--sp-on-primary);';

const css = `${HEADER}
:root,
[data-theme="light"] {
${block(staticVars)}
${block(light)}
${tenantDefaults}
  color-scheme: light;
}

.dark,
[data-theme="dark"] {
${block(dark)}
${tenantDefaults}
  color-scheme: dark;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme]):not(.light) {
${block(dark).replace(/^/gm, '  ')}
  ${tenantDefaults.trim().replace(/\n\s*/g, '\n    ')}
    color-scheme: dark;
  }
}
`;

const colorLines = lightKeys.map((k) => `  --color-${k}: var(--sp-${k});`).join('\n');
const textScale = ['display', 'h1', 'h2', 'body', 'caption']
  .map((k) => {
    const t = primitives[`text.${k}`] as { fontSize: string; lineHeight: string; fontWeight: number };
    return `  --text-${k}: ${t.fontSize};\n  --text-${k}--line-height: ${t.lineHeight};\n  --text-${k}--font-weight: ${t.fontWeight};`;
  })
  .join('\n');

const tailwind = `${HEADER}
/* Dark mode follows the .dark class or data-theme="dark" on any ancestor. */
@custom-variant dark (&:where(.dark, .dark *, [data-theme="dark"], [data-theme="dark"] *));

@theme inline {
  /* Only semantic colours are available as utilities — the default palette is removed on purpose. */
  --color-*: initial;
  --color-transparent: transparent;
  --color-current: currentColor;
  --color-white: #FFFFFF;
${colorLines}
  --color-tenant: var(--sp-tenant-accent);
  --color-on-tenant: var(--sp-on-tenant-accent);

  --font-display: var(--sp-font-display);
  --font-body: var(--sp-font-body);
  --font-mono: var(--sp-font-mono);

${textScale}

  --radius-sm: var(--sp-radius-sm);
  --radius-md: var(--sp-radius-md);
  --radius-lg: var(--sp-radius-lg);
  --radius-full: var(--sp-radius-full);

  --spacing-touch: var(--sp-size-touch);
  --shadow-overlay: var(--sp-shadow-overlay);
}
`;

const json = {
  $generated: 'Generated by @shokfat/design-tokens',
  primitives,
  themes: { light, dark },
};

const ts = `// Generated by @shokfat/design-tokens — do not edit by hand.
export const SEMANTIC_TOKENS = ${JSON.stringify(lightKeys)} as const;
export type SemanticToken = (typeof SEMANTIC_TOKENS)[number];
export const THEMES = ${JSON.stringify({ light, dark }, null, 2)} as const;
`;

writeFileSync(join(dist, 'tokens.css'), css);
writeFileSync(join(dist, 'tailwind-theme.css'), tailwind);
writeFileSync(join(dist, 'tokens.json'), JSON.stringify(json, null, 2) + '\n');
writeFileSync(join(pkg, 'src', 'generated.ts'), ts);

console.log(`design-tokens: ${lightKeys.length} semantic tokens × 2 themes → dist/tokens.css, dist/tailwind-theme.css, dist/tokens.json`);
